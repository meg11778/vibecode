/* Build the weights block for ohhell.html from a trained network.
     node embed.js net_best.json > netdata.js
     node embed.js net2_best.json NET2 > netdata2.js
   16-bit weights, base64. The input scaling is folded into the first layer. */
const j = JSON.parse(require('fs').readFileSync(process.argv[2], 'utf8'));
const PRE = process.argv[3] || 'NET';        // constant-name prefix: NET for network 1, NET2 for network 2
const [F, H1, H2, O] = j.sizes;
if (H1 !== H2) throw new Error('hidden layers must match');
const W1 = [], W2 = [], W3 = [];
for (let i = 0; i < F; i++) for (let o = 0; o < H1; o++) W1.push(j.W[0][i][o] / j.scale[i]);
for (let i = 0; i < H1; i++) for (let o = 0; o < H2; o++) W2.push(j.W[1][i][o]);
for (let o = 0; o < O; o++) for (let i = 0; i < H2; i++) W3.push(j.W[2][i][o]);     // output-major
function pack(name, w) {
  const mx = w.reduce((a, v) => Math.max(a, Math.abs(v)), 0), s = mx / 32767;
  const buf = Buffer.alloc(w.length * 2);
  w.forEach((v, i) => buf.writeInt16LE(Math.round(v / s), 2 * i));
  const b = buf.toString('base64'), lines = [];
  for (let i = 0; i < b.length; i += 160) lines.push('"' + b.slice(i, i + 160) + '"');
  return { s, text: `const ${name}=[\n${lines.join(',\n')}\n];` };
}
const p1 = pack(PRE + '_W1', W1), p2 = pack(PRE + '_W2', W2), p3 = pack(PRE + '_W3', W3);
console.log(`/* Network weights: ${j.trained_on}. Generated by embed.js; do not edit by hand. */`);
if (PRE === 'NET') console.log(`const NET_H=${H1};`);
console.log(`const ${PRE}_S=[${[p1.s, p2.s, p3.s].join(',')}];`);
console.log(`const ${PRE}_B1=[${j.b[0].map(v=>+v.toFixed(5)).join(',')}];`);
console.log(`const ${PRE}_B2=[${j.b[1].map(v=>+v.toFixed(5)).join(',')}];`);
console.log(`const ${PRE}_B3=[${j.b[2].map(v=>+v.toFixed(5)).join(',')}];`);
console.log(p1.text); console.log(p2.text); console.log(p3.text); console.log('');
